//! The Windows adapters: scoop and winget.
//!
//! Both report what is installed as JSON rather than as text to scrape, which
//! is the whole reason these are the query commands: `scoop list` and
//! `winget list` are human-formatted and rot, `scoop export` and
//! `winget export` are machine formats.
//!
//! Identity differs between them, and neither needs a second namespace the
//! way brew's casks do:
//!
//! - scoop installs one app per name, so the NAME is the identity, folded to
//!   lower case: scoop's namespace is the filesystem's and its manifest
//!   lookup is a case-insensitive filter, so `Ripgrep` and `ripgrep` are one
//!   app. A bucket says where an app comes from, not which app it is, so it
//!   is a field used at install time rather than part of the id.
//! - winget's identity is the `PackageIdentifier` (`Microsoft.PowerShell`),
//!   which is what a row spells and what an export reports. Its display name
//!   is not unique and is never used here.
//!
//! Exercised against the real managers only by the Windows integration job;
//! the unit tests cover the parsing against fixtures.

const std = @import("std");
const json = @import("json");

const backend_mod = @import("backend.zig");
const bootstrap_mod = @import("bootstrap.zig");
const exec = @import("exec.zig");
const manifest_mod = @import("manifest.zig");

const Io = std.Io;
const EnvironMap = std.process.Environ.Map;

pub const Row = manifest_mod.Row;
pub const Diag = manifest_mod.Diag;
pub const Backend = backend_mod.Backend;

pub const Error = error{
    UnknownScoopKey,
    BadScoopValue,
    ScoopNameNotAnApp,
    UnknownWingetKey,
    BadWingetValue,
    WingetNameNotAnIdentifier,
    ScoopQueryFailed,
    ScoopBucketListFailed,
    ScoopInstallFailed,
    WingetQueryFailed,
    WingetInstallFailed,
    UnreadableExport,
};

/// What `scoop export` reports about the apps it cannot see the way a row
/// means them: one app directory, dependencies and half-installed apps
/// included.
pub const scoop_limitation = "scoop keeps no record of which apps were asked for, so its export is every app directory and an app installed as a dependency reads untracked";

/// One `apps[]` entry of a `scoop export` document.
pub const App = struct {
    /// The app directory's own name, as scoop reports it.
    name: []const u8,
    /// The bucket the install came from, or the URL or `<auto-generated>`
    /// scoop names in its place; empty when the export has neither.
    source: []const u8 = "",
    failed: bool = false,
    held: bool = false,
    global: bool = false,
};

/// The `Info` clauses `scoop-list.ps1` joins with ", ", and so the ones a
/// `scoop export` carries.
const info_failed = "Install failed";
const info_held = "Held package";
const info_global = "Global install";

/// What `scoop bucket list` exits with when there are no buckets at all --
/// the only nonzero exit that branch has.
const no_buckets_code: u8 = 2;

/// `scoop export` emits `{"apps":[{"Name":...,"Info":...,"Source":...}],...}`.
pub const Scoop = struct {
    runner: exec.Runner,
    /// Where scoop lands (`<home>\scoop\shims`), so a bootstrap can name the
    /// bin dir for this same run. Empty means unknown.
    home: []const u8 = "",
    /// The environment mox itself runs under, read for `$env:SCOOP`: the
    /// installer puts scoop there instead of under the profile, so the shims
    /// are under it too. Null falls back to the profile.
    env: ?*const EnvironMap = null,
    /// How scoop is invoked: `scoop` until a bootstrap installs it, then its
    /// own shim script through pwsh, because a child's PATH is never used to
    /// resolve argv[0] and a freshly installed scoop is on no PATH yet.
    argv0: []const []const u8 = &.{"scoop"},
    /// Whether the last `install` ran `scoop install`, which `installSpawned`
    /// answers with: a `bucket list` that fails stops the batch before any
    /// install, and nothing it named can have landed.
    spawned: bool = false,
    /// How many of the last `install`'s rows scoop was never handed, which
    /// `installRefused` answers with.
    refused: usize = 0,
    /// The export this run read, so `declare` can name the bucket an app came
    /// from and `install` can tell a half-installed app from an absent one.
    /// Null until a query has run.
    apps: ?[]const App = null,
    /// Where a refused row is said. The install's own error is what the call
    /// site reports, so the row and what to do about it have nowhere else to
    /// go.
    err: ?*Io.Writer = null,
    /// Only the bootstrap path needs this: looking for a shim before running
    /// one, so a fresh machine's bootstrap does not print a PowerShell error
    /// about a script that was never going to be there.
    io: ?Io = null,

    pub fn backend(self: *Scoop) Backend {
        return .{
            .name = "scoop",
            .ctx = self,
            .vtable = &vtable,
            .limitation = scoop_limitation,
            .install_check = "the apps scoop already has, and the buckets scoop knows where to clone",
        };
    }

    const vtable: Backend.VTable = .{
        .available = availableImpl,
        .validate = validateImpl,
        .idOf = idOfImpl,
        .installedExplicit = installedExplicitImpl,
        .install = installImpl,
        .installSpawned = installSpawnedImpl,
        .installRefused = installRefusedImpl,
        .declare = declareImpl,
        .bootstrap = bootstrapImpl,
    };

    /// scoop installs itself from a PowerShell script mox has already fetched
    /// and verified -- unless it is already here and merely off this run's
    /// PATH, which is what `adopt` answers.
    fn bootstrapImpl(ctx: *anyopaque, arena: std.mem.Allocator, installer_path: []const u8) anyerror!?[]const u8 {
        const self: *Scoop = @ptrCast(@alignCast(ctx));
        // The installer's PATH edit is a registry write plus its own session,
        // so a terminal opened before it never sees the shims and a second
        // apply in that terminal probes scoop as absent. Running the
        // installer again over a scoop that is there is refused ("exists and
        // is not empty"), so what is there is adopted instead.
        if (try self.adopt(arena)) |shims| return shims;
        const res = try exec.runPowerShell(self.runner, arena, &.{installer_path}, null, true);
        try exec.checkTimedOut(res);
        if (!res.ok) return bootstrap_mod.Error.BootstrapFailed;
        const root = (try self.rootOf(arena)) orelse return null;
        const shims = try std.fs.path.join(arena, &.{ root, "shims" });
        try self.useShim(arena, shims);
        return shims;
    }

    /// The shims directory of a scoop already on this machine, or null.
    ///
    /// Asked by running the shim rather than by looking for the file: what
    /// every call after this one needs is a shim that answers, and a root
    /// left behind by a half-finished install has the directory without one.
    fn adopt(self: *Scoop, arena: std.mem.Allocator) !?[]const u8 {
        const root = (try self.rootOf(arena)) orelse return null;
        const shims = try std.fs.path.join(arena, &.{ root, "shims" });
        if (self.io) |io| {
            const shim = try std.fs.path.join(arena, &.{ shims, "scoop.ps1" });
            Io.Dir.cwd().access(io, shim, .{}) catch return null;
        }
        const before = self.argv0;
        try self.useShim(arena, shims);
        const res = self.call(arena, &.{"--version"}, false) catch {
            self.argv0 = before;
            return null;
        };
        if (res.timed_out or !res.ok) {
            self.argv0 = before;
            return null;
        }
        return shims;
    }

    /// Reach scoop through its own shim script from here on.
    fn useShim(self: *Scoop, arena: std.mem.Allocator, shims: []const u8) !void {
        const shim = try std.fs.path.join(arena, &.{ shims, "scoop.ps1" });
        self.argv0 = try exec.powerShellArgv(arena, exec.powershell_hosts[0], &.{shim});
    }

    /// Where scoop lives: what `SCOOP` names when it is set -- the installer
    /// obeys it, so probing the profile instead would miss the shims it just
    /// wrote -- else `<home>\scoop`. Null when neither is known.
    fn rootOf(self: *const Scoop, arena: std.mem.Allocator) !?[]const u8 {
        if (self.env) |m| {
            if (m.get("SCOOP")) |v| {
                const root = std.mem.trim(u8, v, " \t\r\n");
                if (root.len > 0) return root;
            }
        }
        if (self.home.len == 0) return null;
        const under_profile = try std.fs.path.join(arena, &.{ self.home, "scoop" });
        return under_profile;
    }

    fn argv(self: *const Scoop, arena: std.mem.Allocator, rest: []const []const u8) ![]const []const u8 {
        var out: std.ArrayList([]const u8) = .empty;
        try out.appendSlice(arena, self.argv0);
        try out.appendSlice(arena, rest);
        return out.toOwnedSlice(arena);
    }

    /// Every scoop call goes through `invoke`: once a bootstrap has made
    /// argv0 a PowerShell script, the host is found by trying.
    fn call(self: *const Scoop, arena: std.mem.Allocator, rest: []const []const u8, streamed: bool) anyerror!exec.Result {
        return self.runner.invoke(arena, try self.argv(arena, rest), null, streamed);
    }

    fn availableImpl(ctx: *anyopaque, arena: std.mem.Allocator) anyerror!Backend.Availability {
        const self: *Scoop = @ptrCast(@alignCast(ctx));
        return Backend.probeAvailability("scoop --version", self.call(arena, &.{"--version"}, false));
    }

    /// A row names one app, and takes `bucket` alone.
    ///
    /// scoop takes a manifest path or a URL wherever an app name goes, so a
    /// row could otherwise install a manifest from anywhere; `scoop install
    /// git@2.1` installs a version that `scoop export` reports under the bare
    /// name, which reads as missing on every status after. The bucket is a
    /// field rather than part of the name, so nothing in a name needs a `/`.
    ///
    /// The bucket is held to the same class, because it lands in the same
    /// place: `scoop bucket add <bucket>` takes the bucket's repository as a
    /// SECOND operand, and scoop is a PowerShell script -- whose `-File`
    /// parser is not the one Zig serializes an argv for, so a value carrying
    /// whitespace and a `"` together can leave its own argument and supply
    /// that second operand itself.
    fn validateImpl(_: *anyopaque, row: Row, diag: ?*Diag) anyerror!void {
        if (backend_mod.nameProblem(row.name, .app)) |problem| {
            if (diag) |d| d.set(
                "{s}: row \"{s}\": scoop rows name an app: {s}",
                .{ row.label, row.name, problem.text(.app) },
            );
            return Error.ScoopNameNotAnApp;
        }
        for (row.fields) |p| {
            if (std.mem.eql(u8, p.key, "bucket")) {
                if (p.value != .string) {
                    if (diag) |d| d.set(
                        "{s}: row \"{s}\": \"bucket\" must be a string",
                        .{ row.label, row.name },
                    );
                    return Error.UnknownScoopKey;
                }
                if (backend_mod.valueProblem(p.value.string, .token)) |problem| {
                    if (diag) |d| d.set(
                        "{s}: row \"{s}\": \"bucket\" names a bucket, and a bucket name {s}",
                        .{ row.label, row.name, problem.text(.token) },
                    );
                    return Error.BadScoopValue;
                }
                continue;
            }
            if (diag) |d| d.set(
                "{s}: row \"{s}\": scoop accepts no key \"{s}\" (scoop rows take \"bucket\")",
                .{ row.label, row.name, p.key },
            );
            return Error.UnknownScoopKey;
        }
    }

    /// The app name folded to lower case. scoop installs one app per name
    /// regardless of which bucket supplied it, so a bucket-qualified row and
    /// a bare one naming the same app are the same package -- and so are two
    /// spellings that differ only in case, which is why the fold is here
    /// rather than in the core: an id stays opaque to everything that
    /// compares it.
    fn idOfImpl(_: *anyopaque, arena: std.mem.Allocator, row: Row) anyerror![]const u8 {
        return foldId(arena, row.name);
    }

    fn installedExplicitImpl(ctx: *anyopaque, arena: std.mem.Allocator) anyerror![]const []const u8 {
        const self: *Scoop = @ptrCast(@alignCast(ctx));
        const res = try self.call(arena, &.{"export"}, false);
        try exec.checkTimedOut(res);
        if (!res.ok) return Error.ScoopQueryFailed;
        const apps = try exportApps(arena, res.stdout);
        self.apps = apps;

        var out: std.ArrayList([]const u8) = .empty;
        for (apps) |app| {
            // An app whose install failed is a directory and nothing usable.
            // Reading it as installed is what keeps it broken: scoop's own
            // repair runs inside `scoop install <app>`, which never runs
            // while the row it belongs to reads as satisfied.
            if (app.failed) continue;
            try out.append(arena, try foldId(arena, app.name));
        }
        return out.toOwnedSlice(arena);
    }

    fn installImpl(ctx: *anyopaque, arena: std.mem.Allocator, rows: []const Row) anyerror!void {
        const self: *Scoop = @ptrCast(@alignCast(ctx));
        self.spawned = false;
        self.refused = 0;

        // What the machine has. A row is here because the export did not
        // report its app, and for an app scoop has at all that means a failed
        // install -- which decides whether mox may hand it to scoop.
        const apps = self.apps orelse blk: {
            const res = try self.call(arena, &.{"export"}, false);
            // Captured inside a streamed verb, so it answers to the capture
            // bound; the install's call site knows only the install bound.
            try exec.checkCaptureTimedOut(res);
            if (!res.ok) return Error.ScoopQueryFailed;
            const parsed = try exportApps(arena, res.stdout);
            self.apps = parsed;
            break :blk parsed;
        };

        // A bucket must exist before an app in it can resolve, exactly as a
        // brew tap must, and `scoop bucket add` fails (exit 2) on one already
        // present, so the ones present are listed once and never re-added.
        var listed: std.StringHashMapUnmanaged(void) = .empty;
        var known: ?std.StringHashMapUnmanaged(void) = null;
        for (rows) |row| {
            if (bucketOf(row) == null) continue;
            const res = try self.call(arena, &.{ "bucket", "list" }, false);
            try exec.checkCaptureTimedOut(res);
            // A machine with no buckets at all answers that way, and it is
            // the one state a row naming a bucket repairs: reading it as a
            // failure gives up exactly where mox could help.
            if (!res.ok and res.code != no_buckets_code) return Error.ScoopBucketListFailed;
            if (res.ok) listed = try bucketNames(arena, res.stdout);
            break;
        }

        // One row at a time, and every row is attempted: one app that fails
        // to resolve must not stop the rest of the set.
        var failed = false;
        for (rows) |row| {
            if (try self.refuseBrokenApp(row, apps)) {
                self.refused += 1;
                continue;
            }
            if (bucketOf(row)) |bucket| {
                if (!listed.contains(bucket)) {
                    if (!try self.bucketKnown(arena, &known, bucket)) {
                        self.sayUnknownBucket(row, bucket);
                        self.refused += 1;
                        continue;
                    }
                    const added = try self.call(arena, &.{ "bucket", "add", bucket }, true);
                    try exec.checkTimedOut(added);
                    if (!added.ok) {
                        failed = true;
                        continue;
                    }
                    try listed.put(arena, bucket, {});
                }
            }
            const target = if (bucketOf(row)) |bucket|
                try std.fmt.allocPrint(arena, "{s}/{s}", .{ bucket, row.name })
            else
                row.name;
            self.spawned = true;
            // `scoop-install.ps1` runs `scoop-update.ps1` first unless this is
            // passed, so installing one app would git-pull scoop and every
            // bucket. A row declares presence, not currency.
            const res = try self.call(arena, &.{ "install", "--no-update-scoop", target }, true);
            try exec.checkTimedOut(res);
            if (!res.ok) failed = true;
        }
        if (failed) return Error.ScoopInstallFailed;
    }

    /// Whether this row names an app scoop has in a state mox must not
    /// install over, and say so if it does.
    ///
    /// `scoop install` repairs a failed install (`ensure_none_failed` resets
    /// or purges it first), which is why a failed app is left out of the
    /// installed set and its row reinstalled. Two of them are not mox's to
    /// repair: the repair ignores a hold, which is the user's decision, and
    /// mox never passes `--global`, so repairing a global app here would
    /// leave a second copy under this user instead.
    fn refuseBrokenApp(self: *Scoop, row: Row, apps: []const App) !bool {
        const app = appOf(apps, row.name) orelse return false;
        if (!app.failed) return false;
        if (app.held) {
            self.say(
                "mox: scoop: {s}: row \"{s}\": scoop has it as a held package whose install failed, and repairing it would undo the hold; run \"scoop unhold {s}\" to let mox repair it, or \"scoop reset {s}\" yourself\n",
                .{ row.label, row.name, app.name, app.name },
            );
            return true;
        }
        if (app.global) {
            self.say(
                "mox: scoop: {s}: row \"{s}\": scoop has it as a global install whose install failed, and mox installs for this user alone, so installing here would leave a second copy; run \"scoop reset {s} --global\" yourself\n",
                .{ row.label, row.name, app.name },
            );
            return true;
        }
        return false;
    }

    /// Whether scoop knows where to clone `bucket` from.
    ///
    /// `scoop bucket add <name>` takes the repository as a second operand and
    /// falls back to its own `buckets.json` when there is none, so a bucket
    /// outside that list can only be added with a URL -- which a row cannot
    /// spell, since a bucket value is one token. Asked once per batch, and
    /// only for a bucket that is not already there.
    ///
    /// A query that cannot be run or that fails reads as "known", so a bucket
    /// that would have been added is never refused over a check that could
    /// not answer; scoop refuses it itself in that case, in its own words. A
    /// query killed at its bound is the batch's failure, as `bucket list`'s
    /// is.
    fn bucketKnown(
        self: *Scoop,
        arena: std.mem.Allocator,
        cache: *?std.StringHashMapUnmanaged(void),
        bucket: []const u8,
    ) !bool {
        if (cache.* == null) {
            const res = self.call(arena, &.{ "bucket", "known" }, false) catch return true;
            try exec.checkCaptureTimedOut(res);
            if (!res.ok) return true;
            cache.* = try bucketNames(arena, res.stdout);
        }
        return cache.*.?.contains(bucket);
    }

    fn sayUnknownBucket(self: *Scoop, row: Row, bucket: []const u8) void {
        self.say(
            "mox: scoop: {s}: row \"{s}\": scoop does not know a bucket \"{s}\" and a row cannot name the repository to clone it from; run \"scoop bucket add {s} <repository>\" once and mox will use it\n",
            .{ row.label, row.name, bucket, bucket },
        );
    }

    /// Say `fmt` where a refused row can be read, if anywhere.
    fn say(self: *Scoop, comptime fmt: []const u8, args: anytype) void {
        const w = self.err orelse return;
        w.print(fmt, args) catch return;
        w.flush() catch return;
    }

    fn installSpawnedImpl(ctx: *anyopaque) bool {
        const self: *Scoop = @ptrCast(@alignCast(ctx));
        return self.spawned;
    }

    fn installRefusedImpl(ctx: *anyopaque) usize {
        const self: *Scoop = @ptrCast(@alignCast(ctx));
        return self.refused;
    }

    /// The row that names an observed app: its own spelling, plus the bucket
    /// it came from.
    ///
    /// A bucket is provenance rather than identity, but a machine without it
    /// has no manifest for the app: `scoop install firefox` there aborts with
    /// "Couldn't find manifest". So the row carries where the app came from,
    /// and `idOf` folds the name back to the id this was asked about.
    fn declareImpl(ctx: *anyopaque, arena: std.mem.Allocator, id: []const u8) anyerror!Backend.Declaration {
        const self: *Scoop = @ptrCast(@alignCast(ctx));
        const apps = self.apps orelse return .{ .name = id };
        const app = appOf(apps, id) orelse return .{ .name = id };
        // `main` is on every machine the installer touched, so naming it
        // would add a field that says nothing. A `Source` that is a URL or
        // `<auto-generated>` names no bucket at all, and a row carrying one
        // is refused when the manifest loads.
        if (app.source.len == 0 or std.mem.eql(u8, app.source, "main")) return .{ .name = app.name };
        if (backend_mod.valueProblem(app.source, .token) != null) return .{ .name = app.name };
        const fields = try arena.alloc(manifest_mod.Pair, 1);
        fields[0] = .{ .key = "bucket", .value = .{ .string = app.source } };
        return .{ .name = app.name, .fields = fields };
    }
};

/// The exported app whose name is `name`, compared the way scoop compares
/// one.
fn appOf(apps: []const App, name: []const u8) ?App {
    for (apps) |app| {
        if (std.ascii.eqlIgnoreCase(app.name, name)) return app;
    }
    return null;
}

/// An app name as an id: ASCII lower case. scoop's app names come from
/// manifest filenames, which Windows compares without case, and the bytes
/// above 0x7f are left alone because no such fold is the filesystem's.
fn foldId(arena: std.mem.Allocator, name: []const u8) ![]const u8 {
    const out = try arena.alloc(u8, name.len);
    for (name, out) |c, *o| o.* = std.ascii.toLower(c);
    return out;
}

fn bucketOf(row: Row) ?[]const u8 {
    const f = row.field("bucket") orelse return null;
    return switch (f) {
        .string => |s| if (s.len == 0) null else s,
        else => null,
    };
}

/// `s` with its ANSI escape sequences removed.
///
/// PowerShell 7 colours a table's header and rule with SGR sequences whatever
/// stdout is -- `$PSStyle.OutputRendering` strips them from a host's own
/// writes, not from a formatted table -- so the first token of a header line
/// arrives as `\x1b[32;1mName` and the rule is not all `-`.
fn stripAnsi(arena: std.mem.Allocator, s: []const u8) ![]const u8 {
    if (std.mem.indexOfScalar(u8, s, 0x1b) == null) return s;
    var out: std.ArrayList(u8) = .empty;
    var i: usize = 0;
    while (i < s.len) {
        if (s[i] == 0x1b and i + 1 < s.len and s[i + 1] == '[') {
            var j = i + 2;
            while (j < s.len and !std.ascii.isAlphabetic(s[j])) j += 1;
            i = if (j < s.len) j + 1 else j;
            continue;
        }
        try out.append(arena, s[i]);
        i += 1;
    }
    return out.toOwnedSlice(arena);
}

/// The bucket names of a `scoop bucket list` or a `scoop bucket known`: one
/// per line, the name first. A bucket list prints a table
/// (`Name Source Updated Manifests`) with a header and a dashed rule, which
/// are not buckets; a fifth column would make PowerShell print each field on
/// a line of its own as `<field> : <value>` instead, whose field names are
/// not buckets either.
fn bucketNames(arena: std.mem.Allocator, text: []const u8) !std.StringHashMapUnmanaged(void) {
    var out: std.StringHashMapUnmanaged(void) = .empty;
    var it = std.mem.splitScalar(u8, text, '\n');
    while (it.next()) |raw| {
        var toks = std.mem.tokenizeAny(u8, try stripAnsi(arena, raw), " \t\r");
        const first = toks.next() orelse continue;
        // The table's own header, not a bucket. A bucket named `Name`
        // would be skipped with it; scoop's own output cannot tell them
        // apart, and re-adding one that exists is what this avoids.
        if (std.mem.eql(u8, first, "Name")) continue;
        if (std.mem.indexOfNone(u8, first, "-") == null) continue;
        if (toks.next()) |second| {
            if (std.mem.eql(u8, second, ":")) continue;
        }
        try out.put(arena, first, {});
    }
    return out;
}

/// Every `apps[]` entry of a `scoop export` document, `Info` read rather than
/// discarded: `scoop export` runs `scoop-list.ps1` verbatim, which joins
/// `Install failed`, `Global install` and `Held package` into that one field,
/// and an app that carries the first is a directory rather than a package.
fn exportApps(arena: std.mem.Allocator, text: []const u8) ![]const App {
    const v = json.parse(arena, text, .{}) catch return Error.UnreadableExport;
    if (v != .object) return Error.UnreadableExport;
    const apps = v.get("apps") orelse return Error.UnreadableExport;
    if (apps != .array) return Error.UnreadableExport;

    var out: std.ArrayList(App) = .empty;
    for (apps.array) |app| {
        if (app != .object) continue;
        const name = app.get("Name") orelse continue;
        if (name != .string or name.string.len == 0) continue;
        const info = stringOf(app, "Info");
        try out.append(arena, .{
            .name = name.string,
            .source = stringOf(app, "Source"),
            .failed = std.mem.indexOf(u8, info, info_failed) != null,
            .held = std.mem.indexOf(u8, info, info_held) != null,
            .global = std.mem.indexOf(u8, info, info_global) != null,
        });
    }
    return out.toOwnedSlice(arena);
}

/// `obj[key]` when it is a string, else "". An export writes `null` for an
/// app whose install left no record of where it came from.
fn stringOf(obj: json.Value, key: []const u8) []const u8 {
    const v = obj.get(key) orelse return "";
    return if (v == .string) v.string else "";
}

/// What `winget export` answers instead of "what did the user ask for", in
/// both directions.
///
/// Narrower: an export is grouped by source and a package that belongs to
/// none of them is in no group, so `status` reports its row MISSING for ever.
/// `install` asks `winget list` directly, which is why such a row is marked
/// rather than installed.
///
/// Wider: the export is every installed package a configured source can
/// correlate, which is every redistributable and Store app on the machine,
/// none of which anybody declared.
pub const export_limitation = "winget export reports only what a source supplied, so a package installed outside one reads missing, and every other installed package a source knows, so redistributables and Store apps read untracked";

/// `winget export` writes `{"Sources":[{"Packages":[{"PackageIdentifier":...}]}]}`
/// to a FILE rather than to stdout, so this adapter needs a path to hand it
/// and the ability to read one back.
pub const Winget = struct {
    runner: exec.Runner,
    io: Io,
    /// Where an export is staged. mox's own state directory, so a machine
    /// with an unwritable TEMP still works and nothing is left in a shared
    /// location.
    scratch_dir: []const u8,
    /// How many of the last `install`'s rows were converged without an
    /// install, which `installMarked` answers with.
    marked: usize = 0,
    /// Where a marked row is said.
    err: ?*Io.Writer = null,

    pub fn backend(self: *Winget) Backend {
        return .{
            .name = "winget",
            .ctx = self,
            .vtable = &vtable,
            .limitation = export_limitation,
            .install_check = "whether winget already has the package, which its export cannot report",
        };
    }

    const vtable: Backend.VTable = .{
        .available = availableImpl,
        .validate = validateImpl,
        .idOf = idOfImpl,
        .installedExplicit = installedExplicitImpl,
        .install = installImpl,
        .installMarked = installMarkedImpl,
        .declare = declareImpl,
    };

    fn availableImpl(ctx: *anyopaque, arena: std.mem.Allocator) anyerror!Backend.Availability {
        const self: *Winget = @ptrCast(@alignCast(ctx));
        return Backend.probeAvailability("winget --version", self.runner.run(arena, &.{ "winget", "--version" }));
    }

    /// A row names one package identifier, and takes `source`, `scope` and
    /// `override`.
    ///
    /// The identifier is the publisher's own string, so the rule names what
    /// would make it something else -- a path, a URL, a pattern, an option --
    /// rather than the bytes an identifier may hold: a class narrower than
    /// winget's own would refuse a package someone really has.
    ///
    /// `source` is a source name, which is one token, so it is held to the
    /// narrow class. `override` is held to neither, and cannot be: it exists
    /// to hand arguments on to the package's own installer, so the space,
    /// the slash and the quote an installer argument needs are what it is
    /// for. winget is spawned directly, so the only byte it may not hold is
    /// a control byte, which no argv carries intact.
    fn validateImpl(_: *anyopaque, row: Row, diag: ?*Diag) anyerror!void {
        if (backend_mod.nameProblem(row.name, .identifier)) |problem| {
            if (diag) |d| d.set(
                "{s}: row \"{s}\": winget rows name a package identifier: {s}",
                .{ row.label, row.name, problem.text(.identifier) },
            );
            return Error.WingetNameNotAnIdentifier;
        }
        for (row.fields) |p| {
            const known = std.mem.eql(u8, p.key, "source") or
                std.mem.eql(u8, p.key, "scope") or
                std.mem.eql(u8, p.key, "override");
            if (!known) {
                if (diag) |d| d.set(
                    "{s}: row \"{s}\": winget accepts no key \"{s}\" (winget rows take \"source\", \"scope\", \"override\")",
                    .{ row.label, row.name, p.key },
                );
                return Error.UnknownWingetKey;
            }
            if (p.value != .string) {
                if (diag) |d| d.set(
                    "{s}: row \"{s}\": \"{s}\" must be a string",
                    .{ row.label, row.name, p.key },
                );
                return Error.BadWingetValue;
            }
            if (std.mem.eql(u8, p.key, "scope")) {
                const v = p.value.string;
                if (!std.mem.eql(u8, v, "user") and !std.mem.eql(u8, v, "machine")) {
                    if (diag) |d| d.set(
                        "{s}: row \"{s}\": \"scope\" is \"{s}\", not \"user\" or \"machine\"",
                        .{ row.label, row.name, v },
                    );
                    return Error.BadWingetValue;
                }
                continue;
            }
            const class: backend_mod.ValueClass = if (std.mem.eql(u8, p.key, "override")) .command_line else .token;
            if (backend_mod.valueProblem(p.value.string, class)) |problem| {
                if (diag) |d| d.set(
                    "{s}: row \"{s}\": \"{s}\" {s}",
                    .{ row.label, row.name, p.key, problem.text(class) },
                );
                return Error.BadWingetValue;
            }
        }
    }

    /// The `PackageIdentifier`, which is what the row spells.
    fn idOfImpl(_: *anyopaque, _: std.mem.Allocator, row: Row) anyerror![]const u8 {
        return row.name;
    }

    fn installedExplicitImpl(ctx: *anyopaque, arena: std.mem.Allocator) anyerror![]const []const u8 {
        const self: *Winget = @ptrCast(@alignCast(ctx));

        // Named per process: a status running beside an apply must not read
        // the other's half-written export as this machine's state.
        const name = try std.fmt.allocPrint(arena, "winget-export-{d}.json", .{exec.processId()});
        const tmp_dir = try exec.scratchTmpDir(arena, self.scratch_dir);
        const path = try std.fs.path.join(arena, &.{ tmp_dir, name });
        try Io.Dir.cwd().createDirPath(self.io, tmp_dir);
        // A stale export from an interrupted run would otherwise be read as
        // this machine's current state.
        Io.Dir.cwd().deleteFile(self.io, path) catch {};
        // And whatever this run leaves, on every path out: a failed export
        // may still have written part of one.
        defer Io.Dir.cwd().deleteFile(self.io, path) catch {};

        const res = try self.runner.run(arena, &.{
            "winget",                     "export",
            "-o",                         path,
            "--accept-source-agreements",
        });
        try exec.checkTimedOut(res);
        if (!res.ok) return Error.WingetQueryFailed;

        const text = Io.Dir.cwd().readFileAlloc(self.io, path, arena, .limited(8 << 20)) catch
            return Error.UnreadableExport;
        return packageIdentifiers(arena, text);
    }

    /// No `installSpawned`: a row this refuses to install is one the machine
    /// already has, which is convergence rather than a failure, so a batch
    /// that fails did reach winget.
    fn installImpl(ctx: *anyopaque, arena: std.mem.Allocator, rows: []const Row) anyerror!void {
        const self: *Winget = @ptrCast(@alignCast(ctx));
        self.marked = 0;
        var failed = false;
        for (rows) |row| {
            // A row is here because the export did not report the package,
            // and an export reports only what a source supplied. Asking
            // first is what separates a package winget installed from no
            // source from one it really does not have: `winget install`
            // answers the first with "already installed" and a nonzero code,
            // for ever, while the machine has had it all along.
            if (self.isInstalled(arena, row.name) catch false) {
                self.marked += 1;
                self.say(
                    "mox: winget: {s}: row \"{s}\": winget has it already and its export does not report it, so nothing was installed and the row reads missing on every status\n",
                    .{ row.label, row.name },
                );
                continue;
            }
            var argv: std.ArrayList([]const u8) = .empty;
            // `--id` restricts which FIELD is searched, not how it matches:
            // the default is a case-insensitive substring match, so without
            // `--exact` the row `microsoft.powershell` installs
            // `Microsoft.PowerShell` and an id that is a substring of
            // another package's id installs that other package. Either way
            // `winget export` reports an identifier no row spells, so the
            // row is missing and the package untracked on every run after.
            // It is also what `isInstalled` asks with, which could otherwise
            // not confirm what the install put there.
            try argv.appendSlice(arena, &.{ "winget", "install", "--id", row.name, "--exact" });
            if (stringField(row, "source")) |v| try argv.appendSlice(arena, &.{ "--source", v });
            if (stringField(row, "scope")) |v| try argv.appendSlice(arena, &.{ "--scope", v });
            const override = stringField(row, "override");
            if (override) |v| try argv.appendSlice(arena, &.{ "--override", v });
            // A row declares presence, not currency: without this an install
            // of something already there becomes an upgrade.
            try argv.append(arena, "--no-upgrade");
            // Without both, winget stops on a prompt no unattended apply can
            // answer.
            try argv.appendSlice(arena, &.{ "--accept-package-agreements", "--accept-source-agreements" });
            // And the package's own installer may put a window up, which an
            // apply has no terminal to answer and no default bound to end:
            // `--disable-interactivity` refuses winget's own prompts, and
            // `--silent` picks the manifest's silent switch over the
            // with-progress one.
            try argv.append(arena, "--disable-interactivity");
            // Except where the row hands the installer its own command line:
            // `--override` replaces that argument string outright, so the
            // switch `--silent` would have chosen is discarded and the row's
            // value is what decides.
            if (override == null) try argv.append(arena, "--silent");

            const res = try self.runner.stream(arena, argv.items);
            try exec.checkTimedOut(res);
            if (res.ok) continue;
            // A re-query that cannot run is not an answer that the row
            // landed, and not a reason to abandon the rows after it. One
            // that answers yes says the package was already here: mox
            // installed nothing, so counting the row as installed would
            // claim work winget refused to do.
            if (self.isInstalled(arena, row.name) catch false) {
                self.marked += 1;
                self.say(
                    "mox: winget: {s}: row \"{s}\": winget would not install it but reports it is on this machine, so the row is counted as already there rather than installed\n",
                    .{ row.label, row.name },
                );
                continue;
            }
            failed = true;
        }
        if (failed) return Error.WingetInstallFailed;
    }

    /// Whether winget has this identifier installed, asked directly.
    ///
    /// A package `winget export` omits (one installed outside any source) is
    /// declared MISSING, and installing it fails with "already installed" or
    /// "no applicable upgrade" forever. The INSTALL's exit code cannot tell
    /// that apart from a real failure: winget's error space is `0x8A15xxxx`
    /// and only the low byte of an exit status survives `Term.exited`, so
    /// more than one error arrives as any given byte.
    ///
    /// `list`'s exit code can, and is the whole answer: it terminates with
    /// `APPINSTALLER_CLI_ERROR_NO_APPLICATIONS_FOUND` when nothing matches
    /// and exits 0 when something does. Reading its table instead could only
    /// subtract from that -- winget shrinks its widest column to the console
    /// width and ends what it cut with an ellipsis, and the id is the column
    /// that would be cut.
    fn isInstalled(self: *Winget, arena: std.mem.Allocator, id: []const u8) !bool {
        const res = try self.runner.run(arena, &.{
            "winget",  "list",
            "--id",    id,
            "--exact", "--accept-source-agreements",
        });
        try exec.checkCaptureTimedOut(res);
        return res.ok;
    }

    fn installMarkedImpl(ctx: *anyopaque) usize {
        const self: *Winget = @ptrCast(@alignCast(ctx));
        return self.marked;
    }

    /// Say `fmt` where a marked row can be read, if anywhere.
    fn say(self: *Winget, comptime fmt: []const u8, args: anytype) void {
        const w = self.err orelse return;
        w.print(fmt, args) catch return;
        w.flush() catch return;
    }

    fn declareImpl(_: *anyopaque, _: std.mem.Allocator, id: []const u8) anyerror!Backend.Declaration {
        // An export reports the identifier and nothing that distinguishes one
        // install from another, so a recorded row carries the id alone.
        return .{ .name = id };
    }
};

fn stringField(row: Row, key: []const u8) ?[]const u8 {
    const f = row.field(key) orelse return null;
    return switch (f) {
        .string => |s| if (s.len == 0) null else s,
        else => null,
    };
}

/// Every `Sources[].Packages[].PackageIdentifier` of a `winget export`
/// document.
fn packageIdentifiers(arena: std.mem.Allocator, text: []const u8) ![]const []const u8 {
    const v = json.parse(arena, text, .{}) catch return Error.UnreadableExport;
    if (v != .object) return Error.UnreadableExport;
    const sources = v.get("Sources") orelse return Error.UnreadableExport;
    if (sources != .array) return Error.UnreadableExport;

    var out: std.ArrayList([]const u8) = .empty;
    for (sources.array) |src| {
        if (src != .object) continue;
        const pkgs = src.get("Packages") orelse continue;
        if (pkgs != .array) continue;
        for (pkgs.array) |pkg| {
            if (pkg != .object) continue;
            const id = pkg.get("PackageIdentifier") orelse continue;
            if (id != .string or id.string.len == 0) continue;
            try out.append(arena, id.string);
        }
    }
    return out.toOwnedSlice(arena);
}

