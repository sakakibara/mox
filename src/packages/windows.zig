    "\r\n" ++
    "\x1b[32;1mName  \x1b[0m\x1b[32;1m Source                                  \x1b[0m\x1b[32;1m Updated             \x1b[0m\x1b[32;1m Manifests\x1b[0m\r\n" ++
    "\x1b[32;1m----  \x1b[0m \x1b[32;1m------                                  \x1b[0m \x1b[32;1m-------             \x1b[0m \x1b[32;1m---------\x1b[0m\r\n" ++
    "main   https://github.com/ScoopInstaller/Main  2026-09-13 10:00:00      1400\r\n" ++
